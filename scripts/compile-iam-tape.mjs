import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const source = readFileSync("contracts/IamTape.sol", "utf8");
const input = {
  language: "Solidity",
  sources: { "IamTape.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input)));
if (out.errors?.some((e) => e.severity === "error")) {
  console.error(out.errors.map((e) => e.formattedMessage).join("\n"));
  process.exit(1);
}

const art = out.contracts["IamTape.sol"].IamTape;
const abi = art.abi;
const bytecode = `0x${art.evm.bytecode.object}`;

const file = `/* generated by scripts/compile-iam-tape.mjs — do not edit */
export const IAM_TAPE_ABI = ${JSON.stringify(abi, null, 2)} as const;

export const IAM_TAPE_BYTECODE = "${bytecode}" as const;
`;

writeFileSync("src/lib/iam-tape.ts", file);
console.log("wrote src/lib/iam-tape.ts", "bytecode", bytecode.length, "chars");
